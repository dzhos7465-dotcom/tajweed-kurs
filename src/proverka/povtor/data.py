def Q(s, a, word, ans, hl=None, around=(2, 3), why=None, occ=0, whole=False):
    """место в аяте; длинный аят показываем отрывком вокруг слова"""
    d = P(s, a, word, ans, hl=hl, why=why, occ=occ)
    if not whole:
        from common import toks
        n = len(toks(s, a)); f = max(1, d['wi'] + 1 - around[0]); t = min(n, d['wi'] + 1 + around[1])
        if not (f == 1 and t == n): d['ctx'] = (f, t)
    return d

