def _shuffle(key, items, field):
    """Перемешать так, чтобы не было закономерности: нет трёх одинаковых ответов подряд и нет чередования «через один»."""
    r = random.Random('ekzamen-' + key)
    for _ in range(500):
        x = items[:]; r.shuffle(x); v = [str(i.get(field)) for i in x]
        alt = len(v) >= 4 and all(v[i] == v[i % 2] for i in range(len(v))) and v[0] != v[1]
        run3 = any(v[i] == v[i+1] == v[i+2] for i in range(len(v) - 2))
        same = x == items
        if not alt and not run3 and not same: return x
    return x

